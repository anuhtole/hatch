import { NextResponse } from 'next/server';
import { existsSync, readFileSync } from 'fs';
import { join } from 'path';

// GET /api/wiki/living-resume/export
// Returns a print-optimized HTML document. Open in a new tab and use
// browser Print → Save as PDF for a clean resume export.
export async function GET() {
  const resumePath = join(process.cwd(), 'wiki', 'raw', 'resume-anatole-seychal.md');
  let rawContent = '';
  if (existsSync(resumePath)) {
    rawContent = readFileSync(resumePath, 'utf-8');
  }

  // Simple markdown → HTML conversion for the export
  function mdToHtml(md: string): string {
    return md
      .replace(/^# (.+)$/gm, '<h1>$1</h1>')
      .replace(/^## (.+)$/gm, '<h2>$1</h2>')
      .replace(/^### (.+)$/gm, '<h3>$1</h3>')
      .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
      .replace(/\*(.+?)\*/g, '<em>$1</em>')
      .replace(/^- (.+)$/gm, '<li>$1</li>')
      .replace(/(<li>[\s\S]*?<\/li>)/g, '<ul>$1</ul>')
      .replace(/<\/ul>\n<ul>/g, '')
      .replace(/^---$/gm, '<hr>')
      .replace(/\n\n/g, '</p><p>')
      .replace(/^([^<].+)$/gm, '$1')
      .trim();
  }

  const body = mdToHtml(rawContent);

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Anatole Seychal — Resume</title>
  <style>
    @import url('https://fonts.googleapis.com/css2?family=EB+Garamond:wght@400;500;600;700&display=swap');

    * { margin: 0; padding: 0; box-sizing: border-box; }

    body {
      font-family: 'EB Garamond', Georgia, serif;
      font-size: 11pt;
      line-height: 1.55;
      color: #1a1a1a;
      background: #fff;
      max-width: 800px;
      margin: 0 auto;
      padding: 40px 48px;
    }

    h1 {
      font-size: 26pt;
      font-weight: 700;
      color: #1a1a1a;
      margin-bottom: 6px;
      letter-spacing: -0.02em;
    }

    h2 {
      font-size: 13pt;
      font-weight: 700;
      color: #1a1a1a;
      margin: 20px 0 6px;
      padding-bottom: 4px;
      border-bottom: 1.5px solid #1a1a1a;
      text-transform: uppercase;
      letter-spacing: 0.06em;
    }

    h3 {
      font-size: 11pt;
      font-weight: 700;
      color: #1a1a1a;
      margin: 12px 0 2px;
    }

    p {
      margin-bottom: 6px;
      color: #2a2a2a;
    }

    ul {
      padding-left: 18px;
      margin: 4px 0 8px;
    }

    li {
      margin-bottom: 3px;
      color: #2a2a2a;
    }

    hr {
      border: none;
      border-top: 1px solid #ddd;
      margin: 12px 0;
    }

    strong { font-weight: 700; }
    em { font-style: italic; }

    .meta {
      font-size: 10pt;
      color: #555;
      margin-bottom: 20px;
      line-height: 1.7;
    }

    .meta a { color: #555; text-decoration: none; }

    @media print {
      body { padding: 0; }
      h2 { page-break-after: avoid; }
      h3 { page-break-after: avoid; }
    }
  </style>
</head>
<body>
  ${body}
  <div class="meta" style="margin-top:24px; border-top:1px solid #ddd; padding-top:10px; font-size:9pt; color:#888;">
    Generated by Hatch · ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}
  </div>
</body>
</html>`;

  return new NextResponse(html, {
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'Content-Disposition': 'inline; filename="anatole-seychal-resume.html"',
    },
  });
}
